def licsrc(kind,srcs,id):
    if kind=='rec': return 'CC0-1.0', cm[srcs[0]]['page']
    if kind=='gen': return 'AuraSleep original (owned)', f'https://github.com/{REPO}/blob/main/tools/gen.py'
    rec=[s.split(':')[1] for s in srcs if s.startswith('r:')]
    if rec: return 'CC0-1.0 + AuraSleep original', ' | '.join(cm[r]['page'] for r in rec)+f' | https://github.com/{REPO}/blob/main/tools/gen.py'
    return 'AuraSleep original (owned)', f'https://github.com/{REPO}/blob/main/tools/gen.py'
for (id,cat,pro,bun,kind,srcs,tr,en) in sorted(C,key=lambda c:(CATS.index(c[1]),c[3],c[2])):
    path=f"../{'bundled' if bun else 'release'}/{id}.m4a"; b=os.path.getsize(path); h=sha(path)
    L,S=licsrc(kind,srcs,id); d=round(qc[id]['dur'])
    e=dict(id=id,cat=cat,pro=pro,url=BASE+f'{id}.m4a',bytes=b,sha256=h,durationSec=d,loop=True,license=L,source=S,title=dict(tr=tr,en=en))
    if bun: bundled.append(dict(id=id,cat=cat,file=f'bundled/{id}.m4a',bytes=b,sha256=h,durationSec=d,license=L,title=dict(tr=tr,en=en)))
    else: sounds.append(e)
    rows.append((id,cat,pro,bun,kind,srcs,tr,en,L,S,b,d,qc[id]))
